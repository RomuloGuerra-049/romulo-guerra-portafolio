const spanishText = new WeakMap();
let language = localStorage.getItem("portfolio_language") || "es";

function translateTextNode(node) {
  if (!spanishText.has(node)) spanishText.set(node, node.textContent);
  const original = spanishText.get(node);
  const trimmed = original.trim();
  if (!trimmed) return;
  const translated = language === "es" ? trimmed : translations[language]?.[trimmed];
  if (!translated) return;
  node.nodeValue = original.replace(trimmed, translated);
}

function translateTree(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      return ["SCRIPT", "STYLE", "TEXTAREA"].includes(node.parentElement?.tagName)
        ? NodeFilter.FILTER_REJECT
        : NodeFilter.FILTER_ACCEPT;
    },
  });
  while (walker.nextNode()) translateTextNode(walker.currentNode);
  document.documentElement.lang = language;
}

function mountSelector() {
  const host =
    document.querySelector(".header__container") ||
    document.querySelector(".admin-header") ||
    document.querySelector(".portal-topbar") ||
    document.querySelector(".auth-back")?.parentElement ||
    document.body;
  const wrapper = document.createElement("label");
  wrapper.className = "language-selector";
  wrapper.innerHTML = `<span class="visually-hidden">Idioma</span><select aria-label="Idioma">
    <option value="es">ES</option><option value="en">EN</option><option value="it">IT</option>
  </select>`;
  wrapper.querySelector("select").value = language;
  wrapper.querySelector("select").addEventListener("change", (event) => {
    language = event.target.value;
    localStorage.setItem("portfolio_language", language);
    translateTree();
    window.dispatchEvent(new CustomEvent("languagechange", { detail: language }));
  });
  host.append(wrapper);
}

mountSelector();
translateTree();
new MutationObserver((mutations) => {
  for (const mutation of mutations) {
    mutation.addedNodes.forEach((node) => {
      if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
      else if (node.nodeType === Node.ELEMENT_NODE && !node.closest(".language-selector")) translateTree(node);
    });
  }
}).observe(document.body, { childList: true, subtree: true });

export function currentLanguage() {
  return language;
}
